"""Scores every run in experiments/08_constrained_relations/pred/ (and the colleagues' runs for reference) on eval/gold
and writes RESULTS.md (fact scores, per-relation scores) and errors.md (false and missed facts of each constrained run).

  python experiments/08_constrained_relations/summarize.py
Run from the repository root. Uses eval/evaluate.py; spans are matched by overlap, as in experiments/RESULTS.md.
"""
import collections
import json
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).parent
sys.path.insert(0, "eval")
import evaluate as ev  # noqa: E402

DOCS = ("alford2026", "nechaeva2017")
REFERENCE = {"gold__jev-api-guided": "eval/pred/gold__jev-api-guided", "gold__jev-api": "eval/pred/gold__jev-api",
             "gold__openjev": "eval/pred/gold__openjev", "gold__nli_captive_typed_t099": "eval/pred/gold__nli_captive_typed_t099"}
NOTE = {"gold__jev-api-guided": "Jev API, guided (exp. 05), threshold 0.5", "gold__jev-api": "Jev API (exp. 05), threshold 0.5",
        "gold__openjev": "OpenJev 9B local (exp. 04), threshold 0.5",
        "gold__nli_captive_typed_t099": "NLI, best variant (exp. 07), threshold 0.99 chosen on this gold"}


def table(preds):
    out = subprocess.run([sys.executable, "eval/evaluate.py", "score", "--texts", "texts", "--gold", "eval/gold", "--span", "overlap",
                          "--bootstrap", "500", "--pred", *preds.values()], capture_output=True, text=True, encoding="utf-8").stdout
    rows, cur = {}, None
    for line in out.splitlines():
        m = re.match(r"== (\S+)", line)
        if m:
            cur = m.group(1)
        m = re.match(r"(fact|fact_pair)\s+([\d.]+)%\s+([\d.]+)%\s+([\d.]+)%\s+([\d-]+)%\s+(\d+)/(\d+)/(\d+)", line)
        if m and cur:
            rows.setdefault(cur, {})[m.group(1)] = [float(m.group(i)) for i in (2, 3, 4)] + [m.group(5), *map(int, m.group(6, 7, 8))]
    return rows


def fact_sets(run_dir):
    """(gold facts, predicted facts) as sets of (doc, para, subj eid, relation, obj eid), plus eid -> label"""
    gold, pred, label = set(), set(), {}
    for d in DOCS:
        g = json.loads(Path(f"eval/gold/{d}.json").read_text(encoding="utf-8"))
        p = json.loads(Path(f"{run_dir}/{d}.json").read_text(encoding="utf-8"))
        al = ev.align(g["entities"], p["entities"])
        label.update({(d, e["eid"]): e["label"] for e in g["entities"]})
        gold |= {(d, f["para"], f["subj"], f["rel"], f["obj"]) for f in g["facts"]}
        pred |= {(d, f["para"], al.get(f["subj"]) or "?" + f["subj"], f["rel"], al.get(f["obj"]) or "?" + f["obj"]) for f in p["facts"]}
    return gold, pred, label


def per_relation(run_dir):
    gold, pred, _ = fact_sets(run_dir)
    out = {}
    for rel in sorted({f[3] for f in gold | pred}):
        g, p = {f for f in gold if f[3] == rel}, {f for f in pred if f[3] == rel}
        out[rel] = (len(g & p), len(p - g), len(g - p))
    return out


def main():
    runs = {d.name: str(d) for d in sorted((HERE / "pred").iterdir())}
    res = table({**runs, **REFERENCE})
    lines = ["# Results: zero-shot prompting with constrained decoding", "",
             "Generated by `summarize.py`; do not edit by hand. Gold: `eval/gold` (14 paragraphs, 159 mentions, 54 facts; a draft that "
             "still needs a historian's review). Mentions: the gold mentions, so only the relation stage is measured. Spans by overlap. "
             "Fewer than 30 paragraphs: the 95% intervals are wide.", "",
             "| run | fact P | R | F1 | 95% CI | tp / pred / gold | fact-pair F1 | note |", "|---|---|---|---|---|---|---|---|"]
    for name in [*runs, *REFERENCE]:
        r = res.get(name)
        if r:
            f, fp = r["fact"], r["fact_pair"]
            lines.append(f"| {name} | {f[0]:.1f} | {f[1]:.1f} | {f[2]:.1f} | {f[3]}% | {f[4]} / {f[5]} / {f[6]} | {fp[2]:.1f} | {NOTE.get(name, 'constrained LLM, temperature 0, no threshold')} |")
    groups = {}
    for name in runs:
        groups.setdefault(re.sub(r"-r\d+$", "", name), []).append(name)
    lines += ["", "## Mean of the repeats (gpt-oss answers differ between runs even at temperature 0)", "",
              "| variant | runs | fact P | R | F1 | F1 range | fact-pair F1 |", "|---|---|---|---|---|---|---|"]
    for g, members in groups.items():
        rs = [res[m] for m in members if m in res]
        f1 = [r["fact"][2] for r in rs]
        lines.append(f"| {g} | {len(rs)} | {sum(r['fact'][0] for r in rs) / len(rs):.1f} | {sum(r['fact'][1] for r in rs) / len(rs):.1f} | "
                     f"{sum(f1) / len(rs):.1f} | {min(f1):.1f} to {max(f1):.1f} | {sum(r['fact_pair'][2] for r in rs) / len(rs):.1f} |")
    lines += ["", "## Per relation, first repeat (tp / false positives / missed)", ""]
    first = {n: d for n, d in runs.items() if n.endswith("-r1")}
    names = [*first.values(), REFERENCE["gold__jev-api-guided"]]
    rels = sorted({r for n in names for r in per_relation(n)})
    pr = {n: per_relation(n) for n in names}
    short = [Path(n).name for n in names]
    lines += ["| relation | " + " | ".join(short) + " |", "|---|" + "---|" * len(names)]
    for rel in rels:
        lines.append(f"| {rel} | " + " | ".join("/".join(map(str, pr[n].get(rel, (0, 0, 0)))) for n in names) + " |")
    (HERE / "RESULTS.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    err = ["# Errors of the constrained runs (first repeat)", "", "FP = predicted, not in the gold; FN = in the gold, not predicted. Names are the gold labels.", ""]
    for name, run_dir in first.items():
        gold, pred, label = fact_sets(run_dir)
        lab = lambda d, e: label.get((d, e), str(e))
        err += [f"## {name}", "", "**False positives**", ""]
        err += [f"- {f[1]} {lab(f[0], f[2])} | {f[3]} | {lab(f[0], f[4])}" for f in sorted(pred - gold)]
        err += ["", "**Missed**", ""]
        err += [f"- {f[1]} {lab(f[0], f[2])} | {f[3]} | {lab(f[0], f[4])}" for f in sorted(gold - pred)]
        err.append("")
    (HERE / "errors.md").write_text("\n".join(err), encoding="utf-8")
    print("\n".join(lines[:16]))


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    main()
